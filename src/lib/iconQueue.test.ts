import { afterEach, expect, it, vi } from "vitest";
import { IconQueue } from "./iconQueue";
import type { FileIconRequest } from "@/ipc/bindings/FileIconRequest";
const request = (id: string): FileIconRequest => ({ id, name: "x.txt", path: null, is_dir: false, is_symlink: false, pixels: 28 });
const png = "data:image/png;base64,AA==";
afterEach(() => vi.useRealTimers());
it("deduplicates both queued and running identities; unsubscribed rows receive no late answer", async () => {
  vi.useFakeTimers();
  let resolve!: (v: { id: string; image: string }[]) => void;
  const fetch = vi.fn(() => new Promise<{ id: string; image: string }[]>(r => { resolve = r; }));
  const queue = new IconQueue(fetch);
  const old = vi.fn(), current = vi.fn();
  const stop = queue.subscribe(request("same"), old);
  await vi.advanceTimersByTimeAsync(12);
  queue.subscribe(request("same"), current);
  stop(); resolve([{ id: "same", image: png }]);
  await vi.advanceTimersByTimeAsync(1);
  expect(fetch).toHaveBeenCalledTimes(1);
  expect(old).not.toHaveBeenCalled();
  expect(current).toHaveBeenCalledWith(png);
  const warm = vi.fn(); queue.subscribe(request("same"), warm);
  expect(warm).toHaveBeenCalledWith(png);
  expect(fetch).toHaveBeenCalledTimes(1);
});
it("bounds batches/concurrency and removes scrolled-away work before invoking", async () => {
  vi.useFakeTimers();
  const fetch = vi.fn(async (rs: FileIconRequest[]) => rs.map(r => ({ id: r.id, image: png })));
  const queue = new IconQueue(fetch);
  for (let n = 0; n < 1000; n++) queue.subscribe(request(String(n)), () => {})();
  for (let n = 0; n < 40; n++) queue.subscribe(request(String(n)), () => {});
  await vi.advanceTimersByTimeAsync(100);
  expect(fetch.mock.calls.map(([r]) => r.length)).toEqual([16, 16, 8]);
  expect(queue.stats().waiting).toBe(0);
});
it("evicts by entry count and byte budget, expires positive and negative results", async () => {
  vi.useFakeTimers();
  let now = 0;
  const fetch = vi.fn(async (rs: FileIconRequest[]) => rs.map(r => ({ id: r.id, image: r.id === "missing" ? null : png })));
  const queue = new IconQueue(fetch, () => now, 2, 200);
  for (const id of ["a", "b", "c"]) queue.subscribe(request(id), () => {});
  await vi.advanceTimersByTimeAsync(20);
  expect(queue.stats().entries).toBe(2);
  expect(queue.stats().bytes).toBeLessThanOrEqual(200);
  queue.subscribe(request("missing"), () => {});
  await vi.advanceTimersByTimeAsync(20);
  const calls = fetch.mock.calls.length;
  queue.subscribe(request("missing"), () => {});
  expect(fetch).toHaveBeenCalledTimes(calls);
  now = 5001; queue.subscribe(request("missing"), () => {});
  await vi.advanceTimersByTimeAsync(20);
  expect(fetch).toHaveBeenCalledTimes(calls + 1);
  now = 60001; queue.subscribe(request("c"), () => {});
  await vi.advanceTimersByTimeAsync(20);
  expect(fetch).toHaveBeenCalledTimes(calls + 2);
});
it("turns errors and oversized/non-PNG images into quiet fallbacks", async () => {
  vi.useFakeTimers();
  const fetch = vi.fn().mockRejectedValueOnce(new Error("unavailable"))
    .mockResolvedValueOnce([{ id: "b", image: "data:image/svg+xml,bad" }]);
  const queue = new IconQueue(fetch), result = vi.fn();
  queue.subscribe(request("a"), result); await vi.advanceTimersByTimeAsync(20);
  queue.subscribe(request("b"), result); await vi.advanceTimersByTimeAsync(20);
  expect(result.mock.calls).toEqual([[null], [null]]);
});
it("caps the waiting queue even while one batch is stalled", async () => {
  vi.useFakeTimers();
  let finish!: (r: []) => void;
  const fetch = vi.fn(() => new Promise<[]>(resolve => { finish = resolve; }));
  const queue = new IconQueue(fetch);
  const stops = Array.from({ length: 2000 }, (_, n) => queue.subscribe(request(String(n)), () => {}));
  expect(queue.stats().waiting).toBe(512);
  await vi.advanceTimersByTimeAsync(12);
  await vi.advanceTimersByTimeAsync(1000);
  expect(fetch).toHaveBeenCalledTimes(1);
  stops.forEach(stop => stop());
  finish([]); await vi.advanceTimersByTimeAsync(20);
  expect(queue.stats().waiting).toBe(0);
  expect(queue.stats().running).toBe(false);
});
